@Composable
private fun SheetRow(icon: ImageVector, title: String, value: String, trailing: @Composable (() -> Unit)? = null, onClick: () -> Unit) {
    Row(
        Modifier.fillMaxWidth().clickable(onClick = onClick).padding(horizontal = 20.dp, vertical = 14.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Icon(icon, null)
        Spacer(Modifier.width(18.dp))
        Text(title, Modifier.weight(1f), fontSize = 16.sp)
        if (trailing != null) trailing() else
            Text(value, color = MaterialTheme.colorScheme.onSurfaceVariant, fontSize = 14.sp)
    }
}

/** YouTube jaisa settings sheet: Quality, Speed, Captions, Loop, Stats for nerds. */
@Composable
fun PlayerSettingsSheet(info: StreamInfo, initialPage: String = "main", onDismiss: () -> Unit) {
    var page by remember { mutableStateOf(initialPage) }
    var speedDlg by remember { mutableStateOf(false) }
    var stats by remember { mutableStateOf(false) }
    val qualities = remember(info) { Playback.qualities(info) }
    val captions = remember(info) { Playback.captions(info) }
    val tracks = remember(info) { Playback.audioTracks(info) }
    val curTrack = PlayerController.audioTrack ?: remember(info) { Playback.defaultAudioTrack(info) }
    val q = PlayerController.quality

    ModalBottomSheet(onDismissRequest = onDismiss) {
        Column(Modifier.navigationBarsPadding().verticalScroll(rememberScrollState())) {
            when (page) {
                "quality" -> {
                    Text("Quality", Modifier.padding(20.dp), fontSize = 18.sp)
                    OptionRow("Auto (best)", q == null) { PlayerController.changeQuality(null); onDismiss() }
                    qualities.forEach { h ->
                        OptionRow("${h}p", q == h) { PlayerController.changeQuality(h); onDismiss() }
                    }
                }
                "audio" -> {
                    Text("Audio track", Modifier.padding(20.dp), fontSize = 18.sp)
                    tracks.forEach { (id, name) ->
                        OptionRow(name, curTrack == id) { PlayerController.changeAudioTrack(id); onDismiss() }
                    }
                }
                "captions" -> {
                    Text("Captions", Modifier.padding(20.dp), fontSize = 18.sp)
                    OptionRow("Off", PlayerController.caption == null) { PlayerController.changeCaption(null); onDismiss() }
                    captions.forEach { c ->
                        val name = c.displayLanguageName + if (c.isAutoGenerated) " (auto)" else ""
                        OptionRow(name, PlayerController.caption?.content == c.content) { PlayerController.changeCaption(c); onDismiss() }
                    }
                    if (captions.isEmpty()) Text("Is video mein captions nahi hain", Modifier.padding(20.dp), color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
                else -> {
                    SheetRow(Icons.Outlined.Settings, "Quality", if (q != null) "${q}p" else "Auto") { page = "quality" }
                    SheetRow(Icons.Outlined.Speed, "Playback speed", speedLabel(PlayerController.speed)) { speedDlg = true }
                    SheetRow(Icons.Outlined.ClosedCaption, "Captions", PlayerController.caption?.displayLanguageName ?: "Off") { page = "captions" }
                    if (tracks.isNotEmpty()) {
                        SheetRow(
                            Icons.Outlined.RecordVoiceOver, "Audio track",
                            tracks.firstOrNull { it.first == curTrack }?.second ?: "Default",
                        ) { page = "audio" }
                    }
                    SheetRow(
                        Icons.Outlined.Repeat, "Loop video", "",
                        trailing = { Switch(PlayerController.loop, { PlayerController.changeLoop(it) }) },
                        onClick = { PlayerController.changeLoop(!PlayerController.loop) },
                    )
                    SheetRow(Icons.Outlined.Info, "Stats for nerds", "") { stats = true }
                }
            }
        }
    }
    if (speedDlg) SpeedDialog { speedDlg = false }
    if (stats) StatsDialog(info) { stats = false }
}

@Composable
private fun OptionRow(text: String, selected: Boolean, onClick: () -> Unit) {
    Row(
        Modifier.fillMaxWidth().clickable(onClick = onClick).padding(horizontal = 20.dp, vertical = 14.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
    ) {
        Text(text, fontSize = 16.sp, color = if (selected) YtRed else MaterialTheme.colorScheme.onSurface)
        if (selected) Text("✓", color = YtRed)
    }
}

@Composable
private fun StatsDialog(info: StreamInfo, onDismiss: () -> Unit) {
    val ctx = LocalContext.current
    val p = PlayerController.exo
    val vf = p.videoFormat
    val af = p.audioFormat
    val text = buildString {
        appendLine("Video ID: ${info.id}")
        appendLine("Resolution: ${vf?.let { "${it.width}x${it.height}" } ?: "-"}")
        appendLine("Video codec: ${vf?.codecs ?: vf?.sampleMimeType ?: "-"}")
        appendLine("Video bitrate: ${vf?.bitrate?.takeIf { it > 0 }?.let { "${it / 1000} kbps" } ?: "-"}")
        appendLine("Frame rate: ${vf?.frameRate?.takeIf { it > 0 }?.toString() ?: "-"}")
        appendLine("Audio codec: ${af?.codecs ?: af?.sampleMimeType ?: "-"}")
        appendLine("Audio bitrate: ${af?.bitrate?.takeIf { it > 0 }?.let { "${it / 1000} kbps" } ?: "-"}")
        appendLine("Speed: ${speedLabel(PlayerController.speed)}")
        appendLine("Buffered: ${p.bufferedPosition / 1000}s (pos ${p.currentPosition / 1000}s)")
    }
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Stats for nerds") },
        text = { Text(text, fontSize = 13.sp) },
        confirmButton = { TextButton(onClick = onDismiss) { Text("Close") } },
    )
}
